# スライド生成ループ
for slide_data in slides_data:
    slide = prs.slides.add_slide(slide_data["layout"])
    
    # タイトル設定
    if slide.shapes.title:
        slide.shapes.title.text = slide_data["title"]
    
    # コンテンツ（箇条書き）設定
    if "subtitle" in slide_data: # タイトルスライドの場合
        if len(slide.placeholders) > 1:
            slide.placeholders[1].text = slide_data["subtitle"]
    elif "content" in slide_data: # 通常スライドの場合
        tf = slide.shapes.placeholders[1].text_frame
        for i, item in enumerate(slide_data["content"]):
            if i == 0:
                p = tf.paragraphs[0]
            else:
                p = tf.add_paragraph()
            
            p.text = item
            # インデント処理（全角スペースが含まれていればレベルを下げる簡易実装）
            if item.startswith("　-"):
                p.level = 1
                p.text = item.replace("　- ", "").replace("　-", "")

    # ノート設定
    if "notes" in slide_data:
        notes_slide = slide.notes_slide
        text_frame = notes_slide.notes_text_frame
        text_frame.text = slide_data["notes"]

# 保存
file_path = "VR_Ski_Presentation.pptx"
